/** 카테고리 표를 읽어 경로 → 코드로 바꾼다. 못 찾거나 여러 개면 오류로 멈춘다. */
export function resolveRules(catsFile = "scripts/output/cats.json") {
  const cats = JSON.parse(fs.readFileSync(catsFile, "utf8"));
  const resolved = [];
  const problems = [];
  for (const [re, pathStr] of RULES) {
    const hits = cats.filter((c) => (c.category_name || "").includes(pathStr));
    if (!hits.length) { problems.push(`없는 경로: ${pathStr}`); continue; }
    // 여러 개면 가장 짧은(=상위) 것을 쓴다. 경로가 정확히 끝나는 것을 우선.
    const exact = hits.filter((c) => c.category_name.endsWith(pathStr));
    const pick = (exact.length ? exact : hits).sort((a, b) => a.category_name.length - b.category_name.length)[0];
    resolved.push([re, String(pick.category_code), pick.category_name]);
  }
  return { resolved, problems };
}

/** 상품명으로 카테고리를 정한다. 못 정하면 null */
export function makePicker(catsFile) {
  const { resolved, problems } = resolveRules(catsFile);
  if (problems.length) { console.error("[카테고리 규칙 오류]\n  " + problems.join("\n  ")); process.exit(1); }
  return (name) => {
    for (const [re, code, full] of resolved) if (re.test(name)) return { code, full };
    return null;
  };
}
