/**
 * 우리 카테고리 이름 → 쿠팡 필수옵션 목록.
 *
 * 지정한 쿠팡 경로가 정확히 없으면(쿠팡이 중간에 이름을 바꾸기도 한다)
 * 경로 조각을 뒤에서부터 떼며 가장 가까운 실제 경로를 찾는다.
 * 그래도 없으면 missing에 남겨 사람이 보게 한다 — 조용히 아무거나 쓰지 않는다.
 */
export function makeCoupangOptionLookup() {
  const cats = loadCoupangCategories();
  const flat = (t) => String(t).replace(/\s+/g, "");
  // 지정한 경로가 실제로 있어야만 쓴다.
  // 조각을 떼며 근사치를 찾게 했더니 "핫도그"가 "군만두"로, "간장"이 "기타가루"로 붙었다.
  // 틀린 카테고리는 없는 것만 못하므로 정확히 일치할 때만 채택한다.
  const find = (needle) => {
    const hits = cats.filter((c) => flat(c.path).includes(flat(needle)));
    return hits.sort((a, b) => a.path.length - b.path.length)[0] ?? null;
  };

  const resolved = [];
  const missing = [];
  const inexact = [];
  for (const [ours, theirs] of TO_COUPANG) {
    const hit = find(theirs);
    if (!hit) { missing.push(`${ours}  →  ${theirs}`); continue; }
    resolved.push([ours, hit]);
  }
  resolved.sort((a, b) => b[0].length - a[0].length);   // 구체적인 규칙 먼저
  return {
    missing,
    inexact,
    lookup(ourCategoryName) {
      for (const [ours, cat] of resolved) if (ourCategoryName.includes(ours)) return cat;
      return null;
    },
  };
}

/**
 * 쿠팡 필수옵션 값을 만든다.
 *
 * 쿠팡은 카테고리마다 요구 항목이 다르다.
 *   개당 용량/중량 → 상품명의 "500ml", "200g"
 *   개당 수량      → 묶음 안의 낱개 수
 *   수량/총 수량   → 몇 개들이인지
 * 필요한 값을 상품명에서 못 뽑으면 옵션을 만들지 않는다(빈 값보다 미산출이 낫다).
 */
/** 생리대·팬티라이너·탐폰의 사이즈를 상품명에서 뽑는다 */
function sizeFor(optName, name) {
  const t = String(name).replace(/\s+/g, "");
  if (/체내형|탐폰/.test(optName)) {
    if (/슈퍼플러스|수퍼플러스/.test(t)) return "슈퍼플러스";
    if (/슈퍼|수퍼/.test(t)) return "슈퍼";
    if (/레귤러/.test(t)) return "레귤러";
    return "";
  }
  if (/팬티라이너/.test(optName)) {
    if (/롱/.test(t)) return "롱";
    if (/대형/.test(t)) return "대형";
    if (/중형/.test(t)) return "중형";
    if (/소형/.test(t)) return "소형";
    return "일반";
  }
  // 여성위생용품 사이즈
  if (/오버나이트/.test(t)) return "오버나이트";
  if (/슈퍼롱|수퍼롱/.test(t)) return "슈퍼롱";
  if (/대형/.test(t)) return "대형";
  if (/중형/.test(t)) return "중형";
  if (/소형/.test(t)) return "소형";
  if (/롱/.test(t)) return "롱";
  return "";
}

export function buildOptionFor(coupangCat, spec, itemInfo) {
  if (!coupangCat?.options?.length) return null;
  const names = coupangCat.options.map((o) => o.name);
  const isVolume = spec.unitType === "ml" || spec.unitType === "L";
  const isWeight = spec.unitType === "g" || spec.unitType === "kg";
  // 상품명에서 못 뽑으면 조사해 둔 값(item_info)을 쓴다 ("카프리썬 오렌지 50개" → 200ml)
  const perWeight = String(itemInfo?.개당중량 ?? "").trim();
  const perVolume = String(itemInfo?.개당용량 ?? "").trim();
  const per = spec.unitValue ? `${spec.unitValue}${spec.unitType}` : "";

  // 화장지류: "30m 30롤 2팩" → 개당 수량 30, 수량 2 / "90롤" → 개당 수량 90, 수량 1
  const cs = spec.counts ?? [];
  // 낱개 수: 숫자가 둘이면 앞이 낱개 수, 하나뿐이면 그것이 낱개 수이고 묶음은 1이다
  const perCount = names.includes("개당 수량")
    ? (cs.length >= 2 ? cs[0].n : (cs.length === 1 ? cs[0].n : null))
    : null;
  const totalCount = perCount !== null && cs.length < 2 ? 1 : spec.quantity;

  const parts = [];
  const skipped = [];
  for (const n of names) {
    if (n === "수량" || n === "총 수량") { parts.push([n, `${totalCount}개`]); continue; }
    if (n === "길이") { if (!spec.length) { skipped.push(n); continue; } parts.push([n, spec.length]); continue; }
    if (/사이즈/.test(n)) { const v = sizeFor(n, spec.name ?? ""); if (!v) { skipped.push(n); continue; } parts.push([n, v]); continue; }
    if (n === "개당 용량") { const v = (per && isVolume) ? per : perVolume; if (!v) continue; parts.push([n, v]); continue; }
    if (n === "개당 중량") { if (per && isWeight) parts.push([n, per]); else if (perWeight) parts.push([n, perWeight]); continue; }
    if (n === "개당 수량") {
      // 낱개 수를 뜻한다. 총 수량을 그대로 넣으면 "240개=240매"처럼 같은 값이 두 번 들어간다.
      const v = perCount ?? (spec.unitValue && !isVolume && !isWeight ? Number(spec.unitValue) : null);
      if (!v) { skipped.push(n); continue; }
      // 쿠팡은 "개당 수량" 단위로 "개"를 받지 않는다.
      // 카테고리마다 허용 목록이 다른데(개입/롤/매/매입/입/세트) "개입"은 모든 목록에 들어 있다.
      parts.push([n, `${v}개입`]);
      continue;
    }
    if (n === "최소 중량") { if (per && isWeight) parts.push([n, per]); else if (perWeight) parts.push([n, perWeight]); continue; }
    if (n === "최소 용량" || n === "용량") { const v = (per && isVolume) ? per : perVolume; if (!v) continue; parts.push([n, v]); continue; }
    // 색상·사이즈·맛 등 상품명으로 알 수 없는 항목
    if (!coupangCat.options.find((o) => o.name === n)?.bundle) skipped.push(n);
  }
  // 묶음이 아닌 필수 항목을 하나라도 못 채우면 옵션을 만들지 않는다.
  // 반쪽짜리로 보내면 쿠팡이 "필수 추천 옵션을 모두 선택해주세요"로 반려한다.
  if (skipped.length) return null;
  // 묶음(bundle) 항목은 여러 개 중 하나만 있으면 되므로, 하나도 못 채우면 실패로 본다
  const bundleNames = coupangCat.options.filter((o) => o.bundle).map((o) => o.name);
  const filledBundle = parts.some(([n]) => bundleNames.includes(n));
  if (bundleNames.length && !filledBundle) return null;
  if (!parts.length) return null;
  return {
    hasOption: true,
    optionName: `[${parts.map(([n]) => n).join("=")}]`,
    optionValue: parts.map(([, v]) => v).join("="),
  };
}
