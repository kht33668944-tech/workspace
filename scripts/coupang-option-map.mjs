import fs from "fs";

/** 쿠팡 공식 카테고리 정의를 읽는다 (TS 파일이지만 배열 부분만 JSON으로 파싱) */
export function loadCoupangCategories(file = "lib/coupang-category-options.ts") {
  const src = fs.readFileSync(file, "utf8");
  const m = src.match(/export const COUPANG_CATEGORIES: CoupangCategory\[\] = (\[[\s\S]*?\]);/);
  if (!m) throw new Error("쿠팡 카테고리 정의를 못 찾았다");
  return JSON.parse(m[1]);
}

